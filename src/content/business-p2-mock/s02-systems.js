      md: `- **System (Meadows, 2008):** "an interconnected set of elements that is coherently organised in a way that achieves something": elements, interconnections and a function or purpose. The purpose is often the least visible and most important part.
- **Stock and flow:** a stock is an accumulation (carbon in the atmosphere, fish in the sea, trust in a team); flows change it. Stocks change slowly, which is why emissions cuts take time to stabilise temperature.
- **Reinforcing (positive) feedback loop:** change amplifies itself (compound interest, melting ice lowering reflectivity, sprawl increasing car use).
- **Balancing (negative) feedback loop:** change is resisted, moving towards a goal (a thermostat, prices reducing demand).
- **Delay:** time between action and effect; causes overshoot and oscillation.
- **Non-linearity:** effects are not proportional to causes.
- **Emergence:** system behaviour that no single part intends (traffic jams, market crashes).
- **Resilience (Holling, 1973):** the capacity to absorb shocks and keep functioning, distinct from efficiency.
- **Tipping point:** a critical threshold at which a small change produces a large, often irreversible shift (Lenton et al., 2008).
- **Path dependence and lock-in:** past choices constrain future ones; "carbon lock-in" (Unruh, 2000): fossil infrastructure, institutions and habits reinforce each other.
- **Wicked problem (Rittel and Webber, 1973):** no definitive formulation, no stopping rule, solutions are better or worse not right or wrong, every attempt changes the problem, each problem is unique and a symptom of another.
- **Super-wicked problem (Levin et al., 2012):** wicked plus: time is running out; those who seek to solve it also cause it; there is no central authority; policies irrationally discount the future. Climate change is the textbook case.
- **Forecast vs foresight:** a forecast predicts one future; foresight explores several plausible futures.
- **Scenario:** an internally consistent story of how the future might unfold, used to test strategy.
- **Backcasting:** start from a desired future and work back to today's actions (Robinson, 1982).`,
